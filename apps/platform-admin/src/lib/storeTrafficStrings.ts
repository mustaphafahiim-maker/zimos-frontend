export const GOVERNORATE_CODES = Object.keys(GOVERNORATE_NAMES);

export function governorateName(code: string | null | undefined, locale: "en" | "ar", other = "—"): string {
  if (!code) return other;
  const names = GOVERNORATE_NAMES[code];
  return names ? names[locale] : other;
}

/** "EG" → "Egypt" / "مصر" (the browser's names); unknown codes as they are. */
export function countryName(code: string | null | undefined, locale: "en" | "ar"): string {
  if (!code) return "—";
  try {
    return new Intl.DisplayNames([locale], { type: "region" }).of(code.toUpperCase()) ?? code;
  } catch {
    return code;
  }
}

/** 75 000 ms → "1m 15s" (Arabic: د / ث); null → "—". */
export function formatDwell(ms: number | null | undefined, locale: "en" | "ar"): string {
  if (ms === null || ms === undefined) return "—";
  const s = Math.max(0, Math.round(ms / 1000));
  const u = locale === "ar" ? { h: "س", m: "د", s: "ث" } : { h: "h", m: "m", s: "s" };
  if (s < 60) return `${s}${u.s}`;
  const m = Math.floor(s / 60);
  if (m < 60) return `${m}${u.m} ${s % 60}${u.s}`;
  return `${Math.floor(m / 60)}${u.h} ${m % 60}${u.m}`;
}

/** A percent the API sends with one decimal (null: nothing to divide by). */
export function formatRatePct(rate: number | null | undefined): string {
  return rate === null || rate === undefined ? "—" : `${rate}%`;
}

/** The UTM values of a visit on one line ("facebook / cpc / ramadan"); null when it has none. */
export function utmLine(v: { source: string | null; medium: string | null; campaign: string | null; utmContent: string | null; utmTerm: string | null }): string | null {
  const parts = [v.source, v.medium, v.campaign, v.utmContent, v.utmTerm].filter((p): p is string => Boolean(p));
  return parts.length ? parts.join(" / ") : null;
}

/** Which ad click ids came with the visit ("fbclid, gclid"); null for none. */
export function clickIdLine(ids: { gclid: boolean; fbclid: boolean; ttclid: boolean }): string | null {
  const present = (["fbclid", "gclid", "ttclid"] as const).filter((k) => ids[k]);
  return present.length ? present.join(", ") : null;
}
