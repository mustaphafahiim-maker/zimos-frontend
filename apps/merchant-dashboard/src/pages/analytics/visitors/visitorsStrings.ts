export const GOVERNORATE_CODES = Object.keys(GOVERNORATE_NAMES);

export function governorateName(code: string | null | undefined, locale: "en" | "ar", other = "—"): string {
  if (!code) return other;
  const names = GOVERNORATE_NAMES[code];
  return names ? names[locale] : other;
}

/** 75 000 ms → "1m 15s" (Arabic: د / ث); nothing reported → "—". */
export function formatDwell(ms: number | null | undefined, locale: "en" | "ar"): string {
  if (ms === null || ms === undefined) return "—";
  const s = Math.max(0, Math.round(ms / 1000));
  const u = locale === "ar" ? { h: "س", m: "د", s: "ث" } : { h: "h", m: "m", s: "s" };
  if (s < 60) return `${s}${u.s}`;
  const m = Math.floor(s / 60);
  if (m < 60) return `${m}${u.m} ${s % 60}${u.s}`;
  return `${Math.floor(m / 60)}${u.h} ${m % 60}${u.m}`;
}

/** A percent the API sends with one decimal; nothing to divide by is a dash, never 0%. */
export function formatRatePct(rate: number | null | undefined): string {
  return rate === null || rate === undefined ? "—" : `${rate}%`;
}
